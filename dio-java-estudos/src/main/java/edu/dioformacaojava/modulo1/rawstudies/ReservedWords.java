package edu.dioformacaojava.modulo1.rawstudies;

public class ReservedWords {
    /*
        Palavras reservadas são palavras que possuem um significado especial na linguagem Java e não podem ser utilizadas como 
        identificadores (nomes de variáveis, métodos, classes, etc.).
        Elas são utilizadas para definir a estrutura e o comportamento do código, e seu uso é restrito à linguagem Java. 
        Algumas palavras reservadas são: abstract, assert, boolean, break, byte, case, catch, char, class, const, continue, default, 
        do, double, else, enum, extends, final, finally, float, for, goto, if, implements, import, instanceof, 
        int, interface, long, native, new, null, package, private, protected, public, return, short, static, 
        strictfp, super, switch, synchronized, this, throw, throws, transient, try, void, volatile e while.

        -----------------------------------------------------------------------------------------------------------------------------
        
        No controle de pacote a palavra import é usada para importar classes de outros pacotes, 
        permitindo que o código utilize essas classes sem precisar especificar o caminho completo do pacote.

        A palavra package é usada para declarar o pacote ao qual a classe pertence,
        permitindo que o código seja organizado em diferentes pacotes e evitando conflitos de nomes entre classes com o mesmo 
        nome em pacotes diferentes.

        -----------------------------------------------------------------------------------------------------------------------------

        Os modificadores de acesso são palavras reservadas que definem a visibilidade e o nível de acesso de classes, métodos e atributos.
        Existem quatro tipos de modificadores de acesso em Java:

        public: Permite que a classe, método ou atributo seja acessado de qualquer lugar do código, inclusive de outros pacotes.
        private: Permite que a classe, método ou atributo seja acessado apenas dentro da própria classe.
        protected: Permite que a classe, método ou atributo seja acessado dentro do mesmo pacote e por subclasses,
         mesmo que estejam em pacotes diferentes.
        default (sem modificador): Permite que a classe, método ou atributo seja acessado apenas dentro do mesmo pacote.

        -----------------------------------------------------------------------------------------------------------------------------

        Modificadores de classes são palavras reservadas que definem o comportamento e a estrutura de uma classe.
        Existem três tipos de modificadores de classes em Java:

        abstract: Indica que a classe é abstrata e não pode ser instanciada diretamente, devendo ser estendida por outras classes.

        final: Indica que a classe não pode ser estendida por outras classes.

        strictfp: Indica que a classe deve seguir as regras de ponto flutuante estritas.

        extends: Indica que a classe é uma subclasse de outra classe, herdando seus atributos e métodos.

        implements: Indica que a classe implementa uma interface, devendo fornecer implementações para todos os métodos da 
        interface.

        interface: Indica que a classe é uma interface, devendo ser implementada por outras classes.

        native: Indica que o método é implementado em código nativo, geralmente em C ou C++.

        new: Indica que um novo objeto está sendo criado a partir de uma classe.

        static: Indica que o método ou atributo pertence à classe e não a uma instância específica da classe.

        synchronized: Indica que o método ou bloco de código é sincronizado, permitindo que apenas uma thread acesse o código por vez.

        transient: Indica que o atributo não deve ser serializado, ou seja, não deve ser salvo em um arquivo ou 
        transmitido pela rede.

        volatile: Indica que o atributo pode ser modificado por diferentes threads, 
        garantindo que a thread que acessar o atributo veja sempre o valor mais recente.

        -----------------------------------------------------------------------------------------------------------------------------

        Controle de fluxo dentro de um bloco de código são palavras reservadas que definem a execução do código em 
        diferentes condições.
        As palavras reservadas de controle de fluxo em Java são:

        break: Interrompe a execução de um loop ou switch.

        case: Define um caso em um switch.

        default: Define o caso padrão em um switch.

        if: Executa um bloco de código se uma condição for verdadeira.

        else: Executa um bloco de código se a condição do if for falsa.

        for: Executa um bloco de código repetidamente, geralmente usado para loops com contador.

        while: Executa um bloco de código repetidamente enquanto uma condição for verdadeira.

        do: Executa um bloco de código pelo menos uma vez e depois verifica a condição.
        
        continue: Interrompe a iteração atual de um loop e passa para a próxima iteração.
    */
}
